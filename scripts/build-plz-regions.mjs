// Builds lib/plz-print-regions.ts: every German postcode in Bavaria (09) and
// Baden-Württemberg (08), as sorted ranges. Source: OpenPLZ API (openplzapi.org,
// open data from the official municipality directories), fetched state by state,
// so only these two states are downloaded.
//
// Run again when postcodes change (rarely): node scripts/build-plz-regions.mjs
import { writeFileSync } from "node:fs";

const STATES = { "08": "Baden-Württemberg", "09": "Bayern" };
const PAGE_SIZE = 50;

async function codesOf(state) {
  const codes = new Set();
  for (let page = 1; ; page += 1) {
    const response = await fetch(`https://openplzapi.org/de/FederalStates/${state}/Localities?page=${page}&pageSize=${PAGE_SIZE}`, {
      headers: { accept: "application/json" },
      signal: AbortSignal.timeout(20000),
    });
    if (!response.ok) throw new Error(`OpenPLZ ${state} page ${page}: ${response.status}`);
    const rows = await response.json();
    for (const row of rows) {
      if (/^\d{5}$/.test(row.postalCode ?? "") && row.federalState?.key === state) codes.add(Number(row.postalCode));
    }
    const pages = Number(response.headers.get("x-total-pages") ?? page);
    if (page >= pages) break;
  }
  return codes;
}

const all = new Set();
for (const [state, name] of Object.entries(STATES)) {
  const codes = await codesOf(state);
  console.log(`${name}: ${codes.size} postcodes`);
  for (const code of codes) all.add(code);
}

// Neighbouring postcodes form one range. Gaps between them are not filled: a gap can
// belong to another state (e.g. Hessen inside the 63xxx block).
const sorted = [...all].sort((a, b) => a - b);
const ranges = [];
for (const code of sorted) {
  const last = ranges.at(-1);
  if (last && code === last[1] + 1) last[1] = code;
  else ranges.push([code, code]);
}

const body = ranges.map(([from, to]) => (from === to ? `${from}` : `${from},${to}`)).join(" ");
writeFileSync(
  new URL("../lib/plz-print-regions.ts", import.meta.url),
  `// Generated by scripts/build-plz-regions.mjs from the OpenPLZ API (${new Date().toISOString().slice(0, 10)}).
// Every postcode in Bavaria and Baden-Württemberg: ${sorted.length} codes in ${ranges.length} ranges
// ("from,to" or a single code). Do not edit by hand.
export const PRINT_REGION_RANGES = "${body}";
`,
);
console.log(`${sorted.length} codes, ${ranges.length} ranges`);
